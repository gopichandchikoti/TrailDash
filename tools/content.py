"""Validate authored content and generate its bundled last-known-good fallback."""
import argparse
import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "public/traildash.model.json"
FALLBACK = ROOT / "scripts/ContentFallback.gd"


def unique_pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate content key: {key}")
        result[key] = value
    return result


def validate():
    raw = MODEL.read_text(encoding="utf-8")
    model = json.loads(raw, object_pairs_hook=unique_pairs)
    assert model["schemaVersion"] == 1
    default = model["locales"][model["defaultLocale"]]
    for locale, entries in model["locales"].items():
        assert entries.keys() == default.keys(), f"Key parity: {locale}"
        for key, value in entries.items():
            assert isinstance(value, str) and value, key
            assert set(re.findall(r"\{\w+\}", value)) == set(re.findall(r"\{\w+\}", default[key]))
    packed = json.dumps(model, ensure_ascii=False, separators=(",", ":"))
    # Split the JSON before GDScript escaping to avoid splitting an escape sequence.
    parts = [packed[i:i + 70] for i in range(0, len(packed), 70)]
    source = "# Generated by tools/content.py from public/traildash.model.json.\nextends RefCounted\n\n"
    source += "const JSON_TEXT: String = (\n"
    source += " +\n".join("\t" + json.dumps(part, ensure_ascii=False) for part in parts)
    source += "\n)\n"
    return source, len(default)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected, count = validate()
    if args.check:
        def unpack(source):
            pieces = []
            for line in source.splitlines():
                token = line.strip().removeprefix("+ ").removesuffix(" +")
                if token.startswith(('"', "'")):
                    pieces.append(ast.literal_eval(token))
            return "".join(pieces)

        assert unpack(FALLBACK.read_text(encoding="utf-8")) == unpack(expected), "Run tools/content.py"
    else:
        FALLBACK.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Content valid: {count} keys; fallback {'checked' if args.check else 'generated'}")
